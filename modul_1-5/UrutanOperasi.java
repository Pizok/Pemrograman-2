public class UrutanOperasi {
    public static void main(String[] args) {
        int a = -0;
        int b = -0;
        int jumlah = a + b;
        int kali = a * b;
        int pengurangan = b - a;

        System.out.println("Jumlah: " + jumlah);
        System.out.println("Perkalian: " + kali);
        System.out.println("Pengurangan: " + pengurangan);
    }
}